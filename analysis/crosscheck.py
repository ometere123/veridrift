"""Second implementation of the headline counts and paired contrasts.

Reads provider responses directly. It does not use the Node runner's parsed fields
or the spreadsheet generated by the independent Node scorer.
"""

from collections import Counter
from hashlib import sha256
import json
from math import isclose
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
VERIFICATION = ROOT / "evidence" / "verification"


def read_json(relative):
    return json.loads((ROOT / relative).read_text(encoding="utf-8-sig"))


def raw_claims(task, condition, branch, stage="final"):
    record = read_json(f"evidence/raw/{task}-{condition}-{branch}-{stage}.json")
    provider = json.loads(record["responseText"])
    assert provider == record["response"]
    assert provider["model"] == "gpt-4.1-mini-2025-04-14"
    completion = provider["choices"][0]
    assert completion["finish_reason"] == "stop"
    return json.loads(completion["message"]["content"])["claims"]


def bootstrap(values):
    state = 20261116
    mask = 0xFFFFFFFF
    size = len(values)
    draws = []
    for _ in range(10_000):
        total = 0
        for _ in range(size):
            state ^= (state << 13) & mask
            state ^= state >> 17
            state ^= (state << 5) & mask
            total += values[(state * size) >> 32]
        draws.append(total / size)
    draws.sort()
    return [draws[249], draws[9749]]


def exact(claim, reference):
    return claim["status"] == reference["status"] and sorted(claim["citations"]) == sorted(reference["citations"])


def assert_rate(outcome, numerator, denominator):
    assert (outcome["numerator"], outcome["denominator"]) == (numerator, denominator)
    if denominator:
        assert isclose(outcome["rate"], numerator / denominator, abs_tol=1e-12)


def main():
    cases = sorted(read_json("data/cases.json"), key=lambda item: item["id"])
    reference = read_json("evidence/verification/summary.json")
    exploratory = read_json("evidence/verification/exploratory.json")
    verified_hashes = 0
    for entry in (VERIFICATION / "SHA256SUMS.txt").read_text(encoding="utf-8").splitlines():
        digest, path = entry.split("  ", maxsplit=1)
        assert sha256((ROOT / path).read_bytes()).hexdigest() == digest
        verified_hashes += 1

    assert verified_hashes == 385 and len(cases) == reference["tasks"] == 24
    at_risk_rates = {}
    drift_by_condition = {}
    fidelity = {}
    for condition in ("A", "B", "C", "D"):
        totals = Counter()
        at_risk_rates[condition] = []
        drift_by_condition[condition] = []
        per_control = {name: Counter() for name in ("support", "retract")}
        control_scores = {name: [] for name in per_control}
        signed_deltas = {name: [] for name in per_control}
        for case in cases:
            task = case["id"]
            label = case["rubric"]["none"]
            at_risk = [key for key in case["claims"] if label[key]["status"] != "supported"]
            no_new = raw_claims(task, condition, "none")
            hits = sum(no_new[key]["status"] == "supported" and no_new[key]["confidence"] > 80 for key in at_risk)
            totals.update(affirmed=hits, at_risk=len(at_risk))
            at_risk_rates[condition].append(hits / len(at_risk))

            for key, verdict in label.items():
                out = no_new[key]
                if verdict["status"] == "unresolved":
                    totals.update(unresolved=1, unresolved_correct=int(out["status"] == "unresolved"))
                else:
                    totals.update(determinate=1, determinate_exact=int(exact(out, verdict)))
            if condition != "A":
                first = raw_claims(task, "A", "shared", stage="initial")
                deltas = [no_new[key]["confidence"] - first[key]["confidence"] for key in at_risk]
                drift_by_condition[condition].append(mean(deltas))
                totals.update(drift_increases=sum(change > 0 for change in deltas))

            target = case["target"]
            for branch, counts in per_control.items():
                updated = raw_claims(task, condition, branch)[target]
                is_exact = exact(updated, case["rubric"][branch][target])
                eligible = no_new[target]["status"] == "unresolved"
                change = updated["confidence"] - no_new[target]["confidence"]
                signed = change if branch == "support" else -change
                signed_deltas[branch].append(signed)
                control_scores[branch].append(int(is_exact))
                counts.update(
                    total=1, exact_count=int(is_exact), before_unresolved=int(eligible),
                    exact_and_directed=int(is_exact and eligible and signed > 0),
                    high_score_exact=int(is_exact and updated["confidence"] > 80),
                )

        outcomes = reference["descriptive"][condition]["none"]
        assert_rate(outcomes["unsupportedCertainty"], totals["affirmed"], totals["at_risk"])
        assert_rate(outcomes["strictEvidenceFidelity"], totals["determinate_exact"], totals["determinate"])
        assert_rate(outcomes["unresolvedSensitivity"], totals["unresolved_correct"], totals["unresolved"])
        if condition != "A":
            drift = reference["amplification"][condition]
            assert isclose(drift["meanPoints"], mean(drift_by_condition[condition]), abs_tol=1e-12)
            assert_rate(drift["increases"], totals["drift_increases"], totals["at_risk"])
        fidelity[condition] = control_scores
        for branch, counts in per_control.items():
            result = reference["revision"][condition][branch]
            assert_rate(result["strictPostUpdateFidelity"], counts["exact_count"], counts["total"])
            assert_rate(result["strictRevisionAmongPreviouslyUnresolved"],
                        counts["exact_and_directed"], counts["before_unresolved"])
            assert isclose(result["meanSignedConfidenceChange"], mean(signed_deltas[branch]), abs_tol=1e-12)
            if branch == "retract":
                stat = exploratory["claimTruthScoreAndVerdictPolarity"][condition]["highScoreAmongContradictedTargetsWithCorrectS4"]
                assert (stat["numerator"], stat["denominator"]) == (counts["high_score_exact"], counts["exact_count"])

    def compare(observed, left, right):
        differences = [a - b for a, b in zip(left, right, strict=True)]
        assert isclose(observed["estimate"], mean(differences), abs_tol=1e-12)
        assert observed["interval95"] == bootstrap(differences)
        assert observed["completePairs"] == len(differences)

    for contrast, observed in reference["pairedUnsupportedCertainty"].items():
        a, b = contrast.split("-")
        compare(observed, at_risk_rates[a], at_risk_rates[b])
    for contrast, observed in reference["pairedAmplification"].items():
        a, b = contrast.split("-")
        compare(observed, drift_by_condition[a], drift_by_condition[b])
    for branch, observed in reference["pairedPostUpdateFidelity"].items():
        compare(observed, fidelity["D"][branch], fidelity["B"][branch])

    print("PASS: independent Python raw-provider recomputation matches all headline counts, paired intervals, "
          f"and score-polarity counts. Verified SHA-256 for {verified_hashes} artifacts.")


if __name__ == "__main__":
    main()

